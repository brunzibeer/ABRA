"""
COCO evaluator that works in distributed mode.

Mostly copy-paste from https://github.com/pytorch/vision/blob/edfd5a7/references/detection/coco_eval.py
The difference is that there is less copy-pasting from pycocotools
in the end of the file, as python3 can suppress prints with contextlib
"""
import wandb
import os
import contextlib
import copy
import numpy as np
import torch

from pycocotools.cocoeval import COCOeval
from pycocotools.coco import COCO
import pycocotools.mask as mask_util

from groundingdino.util.misc import all_gather

import itertools
from tabulate import tabulate

class CocoEvaluator(object):
    def __init__(self, coco_gt, iou_types, useCats=True, class_names=None):
        assert isinstance(iou_types, (list, tuple))
        coco_gt = copy.deepcopy(coco_gt)
        self.coco_gt = coco_gt

        self.iou_types = iou_types
        self.coco_eval = {}
        for iou_type in iou_types:
            self.coco_eval[iou_type] = COCOeval(coco_gt, iouType=iou_type)
            self.coco_eval[iou_type].useCats = useCats

        self.img_ids = []
        self.eval_imgs = {k: [] for k in iou_types}
        self.useCats = useCats

        self.class_names = class_names

    def update(self, predictions):
        img_ids = list(np.unique(list(predictions.keys())))
        self.img_ids.extend(img_ids)

        for iou_type in self.iou_types:
            results = self.prepare(predictions, iou_type)

            # suppress pycocotools prints
            with open(os.devnull, 'w') as devnull:
                with contextlib.redirect_stdout(devnull):
                    coco_dt = COCO.loadRes(self.coco_gt, results) if results else COCO()
            coco_eval = self.coco_eval[iou_type]

            coco_eval.cocoDt = coco_dt
            coco_eval.params.imgIds = list(img_ids)
            coco_eval.params.useCats = self.useCats
            img_ids, eval_imgs = evaluate(coco_eval)

            self.eval_imgs[iou_type].append(eval_imgs)

    def synchronize_between_processes(self):
        for iou_type in self.iou_types:
            self.eval_imgs[iou_type] = np.concatenate(self.eval_imgs[iou_type], 2)
            create_common_coco_eval(self.coco_eval[iou_type], self.img_ids, self.eval_imgs[iou_type])

    def accumulate(self):
        for coco_eval in self.coco_eval.values():
            coco_eval.accumulate()

    def summarize(self, seen_classes=[]): 
        # Convert to lowercase for case-insensitive matching
        seen_classes_lower = [cls.lower() for cls in seen_classes]
        
        for iou_type, coco_eval in self.coco_eval.items():
            print("IoU metric: {}".format(iou_type))
            coco_eval.summarize()

            stats = coco_eval.stats
            if stats is not None:
                headers = ["AP", "AP50", "AP75", "APs", "APm", "APl"]
                values = [stats[0]*100, stats[1]*100, stats[2]*100,
                        stats[3]*100, stats[4]*100, stats[5]*100]
                table_str = tabulate([values],
                                     headers=headers,
                                     tablefmt="pipe",
                                     floatfmt=".3f",
                                     colalign=("center",) * len(headers))
                print(f"\nEvaluation results for {iou_type}:")
                print(table_str)

            if self.class_names is None or not tabulate:
                continue

            print(f"\nPer-category {iou_type} AP / AP50 / AP75:")
            precisions = coco_eval.eval["precision"]
            results_per_category = []
            
            # Collect APs for seen and unseen classes
            seen_aps = []
            unseen_aps = []
            
            for idx, name in enumerate(self.class_names):
                # AP (media su IoU da 0.50 a 0.95)
                precision = precisions[:, :, idx, 0, -1]
                precision = precision[precision > -1]
                ap = np.mean(precision) if precision.size else float("nan")

                # AP50
                precision50 = precisions[0, :, idx, 0, -1]
                precision50 = precision50[precision50 > -1]
                ap50 = np.mean(precision50) if precision50.size else float("nan")

                # AP75
                precision75 = precisions[5, :, idx, 0, -1]
                precision75 = precision75[precision75 > -1]
                ap75 = np.mean(precision75) if precision75.size else float("nan")

                results_per_category.append((name, ap*100, ap50*100, ap75*100))
                
                # Collect APs for seen/unseen metrics
                if not np.isnan(ap):
                    if name.lower() in seen_classes_lower:
                        seen_aps.append(ap * 100)
                    else:
                        unseen_aps.append(ap * 100)

            # Calculate seen and unseen mAP
            seen_map = np.mean(seen_aps) if seen_aps else float("nan")
            unseen_map = np.mean(unseen_aps) if unseen_aps else float("nan")
            
            print(f"\nSeen mAP ({', '.join(seen_classes)}): {seen_map:.3f}")
            print(f"Unseen mAP (remaining classes): {unseen_map:.3f}")

            headers = ["category", "AP", "AP50", "AP75"]

            table_str = tabulate(
                results_per_category,
                headers=headers,
                tablefmt="pipe",
                floatfmt=".3f",
            )
            print(table_str)
            
            if wandb.run is not None:
                wandb.log({
                    "EVAL/per_class_AP": wandb.Table(
                        data=results_per_category,
                        columns=["category", "AP", "AP50", "AP75"],
                    )
                })
                wandb.log({
                    "EVAL/AP": stats[0] * 100,
                    "EVAL/seen_mAP": seen_map,
                    "EVAL/unseen_mAP": unseen_map,
                })

    def prepare(self, predictions, iou_type):
        if iou_type == "bbox":
            return self.prepare_for_coco_detection(predictions)
        elif iou_type == "segm":
            return self.prepare_for_coco_segmentation(predictions)
        elif iou_type == "keypoints":
            return self.prepare_for_coco_keypoint(predictions)
        else:
            raise ValueError("Unknown iou type {}".format(iou_type))

    def prepare_for_coco_detection(self, predictions):
        coco_results = []
        for original_id, prediction in predictions.items():
            if len(prediction) == 0:
                continue

            boxes = prediction["boxes"]
            boxes = convert_to_xywh(boxes).tolist()
            if not isinstance(prediction["scores"], list):
                scores = prediction["scores"].tolist()
            else:
                scores = prediction["scores"]
            if not isinstance(prediction["labels"], list):
                labels = prediction["labels"].tolist()
            else:
                labels = prediction["labels"]

            coco_results.extend(
                [
                    {
                        "image_id": original_id,
                        "category_id": labels[k],
                        "bbox": box,
                        "score": scores[k],
                    }
                    for k, box in enumerate(boxes)
                ]
            )
        return coco_results

    def prepare_for_coco_segmentation(self, predictions):
        coco_results = []
        for original_id, prediction in predictions.items():
            if len(prediction) == 0:
                continue

            scores = prediction["scores"]
            labels = prediction["labels"]
            masks = prediction["masks"]

            masks = masks > 0.5

            scores = prediction["scores"].tolist()
            labels = prediction["labels"].tolist()

            rles = [
                mask_util.encode(np.array(mask[0, :, :, np.newaxis], dtype=np.uint8, order="F"))[0]
                for mask in masks
            ]
            for rle in rles:
                rle["counts"] = rle["counts"].decode("utf-8")

            coco_results.extend(
                [
                    {
                        "image_id": original_id,
                        "category_id": labels[k],
                        "segmentation": rle,
                        "score": scores[k],
                    }
                    for k, rle in enumerate(rles)
                ]
            )
        return coco_results

    def prepare_for_coco_keypoint(self, predictions):
        coco_results = []
        for original_id, prediction in predictions.items():
            if len(prediction) == 0:
                continue

            boxes = prediction["boxes"]
            boxes = convert_to_xywh(boxes).tolist()
            scores = prediction["scores"].tolist()
            labels = prediction["labels"].tolist()
            keypoints = prediction["keypoints"]
            keypoints = keypoints.flatten(start_dim=1).tolist()

            coco_results.extend(
                [
                    {
                        "image_id": original_id,
                        "category_id": labels[k],
                        'keypoints': keypoint,
                        "score": scores[k],
                    }
                    for k, keypoint in enumerate(keypoints)
                ]
            )
        return coco_results


def convert_to_xywh(boxes):
    xmin, ymin, xmax, ymax = boxes.unbind(1)
    return torch.stack((xmin, ymin, xmax - xmin, ymax - ymin), dim=1)


def merge(img_ids, eval_imgs):
    all_img_ids = all_gather(img_ids)
    all_eval_imgs = all_gather(eval_imgs)

    merged_img_ids = []
    for p in all_img_ids:
        merged_img_ids.extend(p)

    merged_eval_imgs = []
    for p in all_eval_imgs:
        merged_eval_imgs.append(p)

    merged_img_ids = np.array(merged_img_ids)
    merged_eval_imgs = np.concatenate(merged_eval_imgs, 2)

    # keep only unique (and in sorted order) images
    merged_img_ids, idx = np.unique(merged_img_ids, return_index=True)
    merged_eval_imgs = merged_eval_imgs[..., idx]

    return merged_img_ids, merged_eval_imgs


def create_common_coco_eval(coco_eval, img_ids, eval_imgs):
    img_ids, eval_imgs = merge(img_ids, eval_imgs)
    img_ids = list(img_ids)
    eval_imgs = list(eval_imgs.flatten())

    coco_eval.evalImgs = eval_imgs
    coco_eval.params.imgIds = img_ids
    coco_eval._paramsEval = copy.deepcopy(coco_eval.params)


